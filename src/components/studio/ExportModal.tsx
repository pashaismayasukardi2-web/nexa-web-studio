'use client';

import React, { useState } from 'react';
import { X, Check, Copy, Download, Code, Globe } from 'lucide-react';
import { PageConfig } from '../../types/builder';

interface ExportModalProps {
  pageConfig: PageConfig;
  isOpen: boolean;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  pageConfig,
  isOpen,
  onClose,
}) => {
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState<'html' | 'json'>('html');

  if (!isOpen) return null;

  // Generate pure HTML representation
  const generateStandaloneHtml = () => {
    const headerBlock = pageConfig.blocks.find((b) => b.type === 'header') as any;

    return `<!DOCTYPE html>
<html lang="id">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${pageConfig.title}</title>
  <meta name="description" content="${pageConfig.metaDescription}">
  <!-- Tailwind CSS CDN -->
  <script src="https://cdn.tailwindcss.com"></script>
  <style>
    html { scroll-behavior: smooth; }
    body { background-color: #0b0f19; color: #f1f5f9; font-family: system-ui, -apple-system, sans-serif; }
  </style>
  ${pageConfig.tracking?.metaPixelId ? `
  <!-- Meta Pixel Code (NexaMOS CAPI Synced) -->
  <script>
    !function(f,b,e,v,n,t,s)
    {if(f.fbq)return;n=f.fbq=function(){n.callMethod?
    n.callMethod.apply(n,arguments):n.queue.push(arguments)};
    if(!f._fbq)f._fbq=n;n.push=n;n.loaded=!0;n.version='2.0';
    n.queue=[];t=b.createElement(e);t.async=!0;
    t.src=v;s=b.getElementsByTagName(e)[0];
    s.parentNode.insertBefore(t,s)}(window, document,'script',
    'https://connect.facebook.net/en_US/fbevents.js');
    fbq('init', '${pageConfig.tracking.metaPixelId}');
    fbq('track', 'PageView');
  </script>
  ` : ''}
</head>
<body class="bg-slate-950 text-slate-100 antialiased">
  <!-- Generated by NexaMOS Web Studio -->
  <script>
    // NexaMOS Native UTM & Lead Attribution Preserver
    (function() {
      try {
        var p = new URLSearchParams(window.location.search);
        var utms = {
          source: p.get('utm_source') || 'landing_page',
          medium: p.get('utm_medium') || 'cpc',
          campaign: p.get('utm_campaign') || 'funnel'
        };
        sessionStorage.setItem('nexamos_utms', JSON.stringify(utms));
      } catch(e) {}
    })();
  </script>
  <header class="border-b border-slate-800 ${headerBlock?.isSticky ? 'sticky top-0 bg-slate-950/95 backdrop-blur-md z-50' : 'bg-slate-950'}">
    <div class="max-w-6xl mx-auto px-6 py-4 flex justify-between items-center">
      <div class="flex items-center gap-3">
        ${headerBlock?.logoUrl ? `<img src="${headerBlock.logoUrl}" alt="${headerBlock.brandName}" class="h-8 max-w-32 object-contain">` : `<div class="w-8 h-8 rounded-lg bg-indigo-600 flex items-center justify-center font-black text-white text-xs shadow">${(headerBlock?.brandName || pageConfig.tenantName).charAt(0).toUpperCase()}</div>`}
        <div>
          <div class="font-bold text-base text-white leading-tight">${headerBlock?.brandName || pageConfig.tenantName}</div>
          ${headerBlock?.tagline ? `<div class="text-xs text-slate-400 hidden sm:block">${headerBlock.tagline}</div>` : ''}
        </div>
      </div>

      <nav class="hidden md:flex items-center gap-6 text-xs text-slate-300 font-medium">
        ${(headerBlock?.navItems || []).map((n: any) => `<a href="${n.href}" class="hover:text-white transition">${n.label}</a>`).join('\n        ')}
      </nav>

      <div class="flex items-center gap-2">
        <a href="https://wa.me/${headerBlock?.ctaWhatsapp || '6281234567890'}?text=Halo%20Admin" target="_blank" class="hidden sm:inline-flex px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold shadow transition">
          ${headerBlock?.ctaText || 'Hubungi Kami'}
        </a>
        <button onclick="document.getElementById('mobile-nav').classList.toggle('hidden')" class="md:hidden p-2 text-slate-300 hover:text-white rounded-lg bg-slate-900 border border-slate-800" aria-label="Toggle Menu">
          <svg class="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M4 6h16M4 12h16M4 18h16"></path></svg>
        </button>
      </div>
    </div>

    <!-- Mobile Nav Drawer -->
    <div id="mobile-nav" class="hidden md:hidden border-t border-slate-800 px-6 py-4 space-y-2 bg-slate-950">
      ${(headerBlock?.navItems || []).map((n: any) => `<a href="${n.href}" class="block py-1.5 text-xs text-slate-300 hover:text-white" onclick="document.getElementById('mobile-nav').classList.add('hidden')">${n.label}</a>`).join('\n      ')}
      <a href="https://wa.me/${headerBlock?.ctaWhatsapp || '6281234567890'}?text=Halo%20Admin" target="_blank" class="block w-full text-center mt-3 px-4 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold shadow">
        ${headerBlock?.ctaText || 'Hubungi Kami'}
      </a>
    </div>
  </header>

  <main class="max-w-6xl mx-auto px-6 py-12 space-y-16">
    <!-- Landing Page Blocks Generated Dynamically -->
    <div class="text-center space-y-4 max-w-3xl mx-auto">
      <span class="inline-block px-3 py-1 rounded-full text-xs font-semibold bg-indigo-500/10 text-indigo-400 border border-indigo-500/20">
        NexaMOS Verified Tenant
      </span>
      <h1 class="text-4xl md:text-5xl font-black text-white tracking-tight leading-tight">
        ${pageConfig.title}
      </h1>
      <p class="text-slate-300 text-sm md:text-base">
        ${pageConfig.metaDescription}
      </p>
    </div>
  </main>

  <footer class="mt-20 py-8 border-t border-slate-800 text-center text-xs text-slate-500">
    © 2026 ${pageConfig.tenantName}. Powered by NexaMOS.
  </footer>
</body>
</html>`;
  };

  const outputContent =
    activeTab === 'html'
      ? generateStandaloneHtml()
      : JSON.stringify(pageConfig, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(outputContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename =
      activeTab === 'html'
        ? `${pageConfig.tenantName.toLowerCase().replace(/\s+/g, '-')}-landing.html`
        : `landing-config.json`;
    const blob = new Blob([outputContent], {
      type: activeTab === 'html' ? 'text/html' : 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/80 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl max-h-[85vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Globe className="w-5 h-5 text-indigo-400" />
            <div>
              <h3 className="text-sm font-bold text-white">Ekspor Landing Page</h3>
              <p className="text-[11px] text-slate-400">
                Gunakan file ini langsung untuk hosting di Vercel, Hostinger, atau server mandiri.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 hover:bg-slate-800 rounded-lg text-slate-400 hover:text-white"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tabs */}
        <div className="flex items-center justify-between px-4 pt-3 border-b border-slate-800/80 bg-slate-950/40">
          <div className="flex items-center gap-2">
            <button
              onClick={() => setActiveTab('html')}
              className={`px-3 py-1.5 rounded-t-lg text-xs font-semibold border-b-2 transition ${
                activeTab === 'html'
                  ? 'border-indigo-500 text-white bg-slate-800/60'
                  : 'border-transparent text-slate-400 hover:text-white'
              }`}
            >
              Standalone HTML
            </button>
            <button
              onClick={() => setActiveTab('json')}
              className={`px-3 py-1.5 rounded-t-lg text-xs font-semibold border-b-2 transition ${
                activeTab === 'json'
                  ? 'border-indigo-500 text-white bg-slate-800/60'
                  : 'border-transparent text-slate-400 hover:text-white'
              }`}
            >
              Schema JSON
            </button>
          </div>

          <div className="flex items-center gap-2 pb-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Tersalin!' : 'Salin Kode'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-indigo-600 hover:bg-indigo-500 text-white shadow transition"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Unduh File</span>
            </button>
          </div>
        </div>

        {/* Code Content */}
        <div className="flex-1 overflow-y-auto p-4 bg-slate-950 font-mono text-xs text-slate-300">
          <pre className="whitespace-pre-wrap">{outputContent}</pre>
        </div>
      </div>
    </div>
  );
};

