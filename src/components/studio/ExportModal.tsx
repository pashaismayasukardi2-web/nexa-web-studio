'use client';

import React, { useState } from 'react';
import { X, Check, Copy, Download, Code, Globe } from 'lucide-react';
import { PageConfig } from '../../types/builder';

interface ExportModalProps {
  pageConfig: PageConfig;
  isOpen: boolean;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  pageConfig,
  isOpen,
  onClose,
}) => {
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState<'html' | 'json'>('html');

  if (!isOpen) return null;

  // Generate pure HTML representation
  const generateStandaloneHtml = () => {
    return `<!DOCTYPE html>
<html lang="id">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${pageConfig.title}</title>
  <meta name="description" content="${pageConfig.metaDescription}">
  <!-- Tailwind CSS CDN -->
  <script src="https://cdn.tailwindcss.com"></script>
  <style>
    body { background-color: #0b0f19; color: #f1f5f9; font-family: system-ui, -apple-system, sans-serif; }
  </style>
</head>
<body class="bg-slate-950 text-slate-100 antialiased">
  <!-- Generated by NexaMOS Web Studio -->
  <header class="py-4 px-6 border-b border-slate-800 flex justify-between items-center max-w-6xl mx-auto">
    <div class="font-bold text-lg text-white">${pageConfig.tenantName}</div>
    <a href="https://wa.me/6281234567890" class="px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold">
      Hubungi Kami
    </a>
  </header>

  <main class="max-w-6xl mx-auto px-6 py-12 space-y-16">
    <!-- Landing Page Blocks Generated Dynamically -->
    <div class="text-center space-y-4 max-w-3xl mx-auto">
      <span class="inline-block px-3 py-1 rounded-full text-xs font-semibold bg-indigo-500/10 text-indigo-400 border border-indigo-500/20">
        NexaMOS Verified Tenant
      </span>
      <h1 class="text-4xl md:text-5xl font-black text-white tracking-tight leading-tight">
        ${pageConfig.title}
      </h1>
      <p class="text-slate-300 text-sm md:text-base">
        ${pageConfig.metaDescription}
      </p>
    </div>
  </main>

  <footer class="mt-20 py-8 border-t border-slate-800 text-center text-xs text-slate-500">
    © 2026 ${pageConfig.tenantName}. Powered by NexaMOS.
  </footer>
</body>
</html>`;
  };

  const outputContent =
    activeTab === 'html'
      ? generateStandaloneHtml()
      : JSON.stringify(pageConfig, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(outputContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename =
      activeTab === 'html'
        ? `${pageConfig.tenantName.toLowerCase().replace(/\s+/g, '-')}-landing.html`
        : `landing-config.json`;
    const blob = new Blob([outputContent], {
      type: activeTab === 'html' ? 'text/html' : 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/80 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl max-h-[85vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Globe className="w-5 h-5 text-indigo-400" />
            <div>
              <h3 className="text-sm font-bold text-white">Ekspor Landing Page</h3>
              <p className="text-[11px] text-slate-400">
                Gunakan file ini langsung untuk hosting di Vercel, Hostinger, atau server mandiri.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 hover:bg-slate-800 rounded-lg text-slate-400 hover:text-white"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tabs */}
        <div className="flex items-center justify-between px-4 pt-3 border-b border-slate-800/80 bg-slate-950/40">
          <div className="flex items-center gap-2">
            <button
              onClick={() => setActiveTab('html')}
              className={`px-3 py-1.5 rounded-t-lg text-xs font-semibold border-b-2 transition ${
                activeTab === 'html'
                  ? 'border-indigo-500 text-white bg-slate-800/60'
                  : 'border-transparent text-slate-400 hover:text-white'
              }`}
            >
              Standalone HTML
            </button>
            <button
              onClick={() => setActiveTab('json')}
              className={`px-3 py-1.5 rounded-t-lg text-xs font-semibold border-b-2 transition ${
                activeTab === 'json'
                  ? 'border-indigo-500 text-white bg-slate-800/60'
                  : 'border-transparent text-slate-400 hover:text-white'
              }`}
            >
              Schema JSON
            </button>
          </div>

          <div className="flex items-center gap-2 pb-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Tersalin!' : 'Salin Kode'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-indigo-600 hover:bg-indigo-500 text-white shadow transition"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Unduh File</span>
            </button>
          </div>
        </div>

        {/* Code Content */}
        <div className="flex-1 overflow-y-auto p-4 bg-slate-950 font-mono text-xs text-slate-300">
          <pre className="whitespace-pre-wrap">{outputContent}</pre>
        </div>
      </div>
    </div>
  );
};

